#!/usr/bin/env node
/**
 * gen-site-meta.mjs — builds site/demos/generated-meta.ts from the Astro registry:
 * slug → { file, category (lib folder), usage (Astro usage snippet converted to JSX) }.
 *
 * Hand-written entries in site/demos/meta.ts override these.
 * Run after porting new components: node scripts/gen-site-meta.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { transformMarkup, addMapKeys, newCtx } from './astro2react.mjs';
import { deAstro } from './de-astro.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const registry = JSON.parse(fs.readFileSync(path.join(root, 'site/data/registry.json'), 'utf8'));
const astro = JSON.parse(fs.readFileSync(path.join(root, 'scripts/.astro-usage.json'), 'utf8'));
const LIB = path.join(root, 'src/components/lib');
const PKG = 'react-component-kit-ui';

// All component files: { name, folder }
const files = [];
for (const entry of fs.readdirSync(LIB, { withFileTypes: true })) {
  if (entry.isDirectory()) {
    for (const f of fs.readdirSync(path.join(LIB, entry.name))) if (f.endsWith('.tsx')) files.push({ name: f.slice(0, -4), folder: entry.name });
  } else if (entry.name.endsWith('.tsx')) files.push({ name: entry.name.slice(0, -4), folder: '' });
}

const clean = (s) => s.replace(/[^a-zA-Z0-9]/g, '').toLowerCase();
/** Same resolution rules as astro PreviewRenderer.astro. */
function resolveFile(slug) {
  if (slug === 'cart-store') return files.find((f) => f.name === 'CartDrawer');
  const pascal = slug.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
  const cs = clean(slug);
  return (
    files.find((f) => f.name === pascal) ||
    files.find((f) => clean(f.name) === cs) ||
    files.find((f) => clean(f.name).replace(/^threed/, '3d') === cs.replace(/^threed/, '3d')) ||
    files.find((f) => clean(f.name).replace('ui', '') === cs.replace('ui', '')) ||
    (slug.includes('3d') ? files.find((f) => /3d|threed/.test(clean(f.name))) : undefined)
  );
}

function convertUsage(src, file) {
  let markup = src.replace(/^---[\s\S]*?---\s*/m, '').trim();
  markup = markup.replace(/<style[\s\S]*?<\/style>/g, '').replace(/<script[\s\S]*?<\/script>/g, '').trim();
  if (!markup) return `<${file.name} />`;
  const ctx = newCtx();
  let jsx = addMapKeys(transformMarkup(markup, ctx));
  return deAstro(jsx);
}

const out = {};
const missing = [];
for (const c of registry.components) {
  const file = resolveFile(c.slug);
  if (!file) { missing.push(c.slug); continue; }
  const usage = convertUsage(astro.usage[c.slug] ?? '', file);
  out[c.slug] = { file: file.folder ? file.name : file.name, category: file.folder || '.', usage };
}

const ts = `// AUTO-GENERATED by scripts/gen-site-meta.mjs — do not edit (override in meta.ts).
import type { DemoMeta } from './meta-types';

export const generatedMeta: Record<string, DemoMeta> = ${JSON.stringify(out, null, 2)};

/** Preview props for e-commerce / app components. */
export const previewProps: Record<string, { props?: Record<string, unknown>; maxWidth?: string }> = ${JSON.stringify(astro.ecommercePreview, null, 2)};

/** Props for section miniatures inside template pages. */
export const sectionPreviewProps: Record<string, Record<string, unknown>> = ${JSON.stringify(astro.sectionPreviewProps ?? {}, null, 2)};
`;
fs.writeFileSync(path.join(root, 'site/demos/generated-meta.ts'), ts);
console.log(`gen-site-meta: ${Object.keys(out).length} entries${missing.length ? `, unresolved: ${missing.join(', ')}` : ''}`);

// ── Per-folder preview modules (one lazy chunk per category), same rules as PreviewRenderer.astro ──
const MANUAL = new Set(['buttons', 'feedback']);
const autoDir = path.join(root, 'site/demos/auto');
fs.mkdirSync(autoDir, { recursive: true });
const byFolder = {};
for (const [slug, m] of Object.entries(out)) {
  if (MANUAL.has(m.category)) continue;
  (byFolder[m.category] ??= []).push({ slug, file: m.file, name: registry.components.find((c) => c.slug === slug)?.name ?? m.file });
}
for (const [folder, items] of Object.entries(byFolder)) {
  const rel = folder === '.' ? '../../../src/components/lib' : `../../../src/components/lib/${folder}`;
  const uniqueFiles = [...new Set(items.map((i) => i.file))];
  const modName = folder === '.' ? 'root' : folder;
  const code = `'use client';
// AUTO-GENERATED by scripts/gen-site-meta.mjs — previews for lib/${folder}.
/* eslint-disable @typescript-eslint/no-explicit-any */
import type { ComponentType } from 'react';
${uniqueFiles.map((f) => `import ${f} from '${rel}/${f}';`).join('\n')}
import { AutoPreview } from '../AutoPreview';

const C: Record<string, ComponentType<any>> = {
${items.map((i) => `  ${JSON.stringify(i.slug)}: ${i.file},`).join('\n')}
};
const NAMES: Record<string, string> = ${JSON.stringify(Object.fromEntries(items.map((i) => [i.slug, i.name])), null, 2)};

export default function Demo({ slug, bare, props }: { slug: string; bare?: boolean; props?: Record<string, unknown> }) {
  const Comp = C[slug];
  if (Comp && bare) return <Comp {...(props ?? {})} />;
  return Comp ? <AutoPreview slug={slug} name={NAMES[slug]} Comp={Comp} wide={${['charts', 'ecommerce', 'app', 'sections'].includes(folder)}} /> : null;
}
`;
  fs.writeFileSync(path.join(autoDir, `${modName}.tsx`), code);
}
const loaders = Object.keys(byFolder).map((f) => (f === '.' ? 'root' : f));
fs.writeFileSync(path.join(root, 'site/demos/auto/loaders.ts'), `'use client';
// AUTO-GENERATED by scripts/gen-site-meta.mjs
import dynamic from 'next/dynamic';
import type { ComponentType } from 'react';

export const autoLoaders: Record<string, ComponentType<{ slug: string; bare?: boolean; props?: Record<string, unknown> }>> = {
${loaders.map((l) => `  ${JSON.stringify(l === 'root' ? '.' : l)}: dynamic(() => import('./${l}')),`).join('\n')}
};
`);
console.log(`gen-site-meta: preview modules for ${loaders.join(', ')}`);
