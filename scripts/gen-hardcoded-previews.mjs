#!/usr/bin/env node
/**
 * Converts the hand-written previews of astro PreviewRenderer.astro (`{slug === 'x' && (...)}` blocks)
 * into site/demos/HardcodedPreview.tsx, so docs pages show exactly the same demos as astrocomponents.dev.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { transformMarkup, addMapKeys, newCtx } from './astro2react.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = fs.readFileSync(path.join(root, '../astro-components/src/components/docs/PreviewRenderer.astro'), 'utf8');
const hard = JSON.parse(/const hasHardcoded = (\[[^\]]*\])/.exec(src)[1].replace(/'/g, '"'));
const markup = src.split(/^---$/m)[2].replace(/<style[\s\S]*?<\/style>/g, '').replace(/<script[\s\S]*?<\/script>/g, '');

// Pull each `{slug === 'x' && ( ... )}` block with a balanced-paren scan.
const blocks = {};
const re = /\{slug === '([\w-]+)' && \(/g;
let m;
while ((m = re.exec(markup))) {
  if (!hard.includes(m[1])) continue;
  let i = m.index + m[0].length, depth = 1;
  for (; i < markup.length && depth; i++) { if (markup[i] === '(') depth++; else if (markup[i] === ')') depth--; }
  blocks[m[1]] = markup.slice(m.index + m[0].length, i - 1).trim();
}

/** <Comp ...><div slot="x">…</div></Comp> → <Comp ... x={<>…</>}> (Astro named slots → props). */
function slotsToProps(jsx) {
  const first = /<div slot="[\w-]+">/.exec(jsx);
  if (!first) return jsx;
  // opening component tag right before the first slot (no injected props yet, so `>` is safe)
  const open = [...jsx.slice(0, first.index).matchAll(/<([A-Z]\w*)\b[^>]*>/g)].pop();
  const closeTag = `</${open[1]}>`;
  const end = jsx.indexOf(closeTag, first.index);
  let body = jsx.slice(open.index + open[0].length, end);
  const props = [];
  for (;;) {
    const m = /<div slot="([\w-]+)">/.exec(body);
    if (!m) break;
    let depth = 1;
    const tagRe = /<div\b|<\/div>/g;
    tagRe.lastIndex = m.index + m[0].length;
    let t;
    while (depth && (t = tagRe.exec(body))) depth += t[0] === '</div>' ? -1 : 1;
    props.push(`${m[1].replace(/-([a-z])/g, (_, c) => c.toUpperCase())}={<>${body.slice(m.index + m[0].length, t.index).trim()}</>}`);
    body = body.slice(0, m.index) + body.slice(t.index + 6);
  }
  const openTag = open[0].replace(/\s*>$/, ` ${props.join(' ')}>`);
  return slotsToProps(jsx.slice(0, open.index) + openTag + body + jsx.slice(end));
}

const cases = Object.entries(blocks).map(([slug, body]) => {
  const jsx = slotsToProps(addMapKeys(transformMarkup(body, newCtx()))).replace(/\bAstro(?![.\w])/g, 'React');
  return `    case ${JSON.stringify(slug)}:\n      return (\n        <>\n${jsx.split('\n').map((l) => '          ' + l).join('\n')}\n        </>\n      );`;
});

const out = `'use client';
// AUTO-GENERATED by scripts/gen-hardcoded-previews.mjs from astro PreviewRenderer.astro — do not edit.
/* eslint-disable */
import { GlassButton, GlowButton } from '../../src/components/lib/buttons';
import { Badge } from '../../src/components/lib/feedback';
import { GlassCard } from '../../src/components/lib/cards';
import { AnimatedInput, NeumorphicSwitch } from '../../src/components/lib/forms';
import { GlassNavbar } from '../../src/components/lib/navigation';

export const HARDCODED = new Set(${JSON.stringify(Object.keys(blocks))});

export default function HardcodedPreview({ slug }: { slug: string }) {
  switch (slug) {
${cases.join('\n')}
    default:
      return null;
  }
}
`;
fs.writeFileSync(path.join(root, 'site/demos/HardcodedPreview.tsx'), out);
fs.writeFileSync(path.join(root, 'site/demos/hardcoded-slugs.ts'), `// AUTO-GENERATED by scripts/gen-hardcoded-previews.mjs (server-safe list)\nexport const HARDCODED_SLUGS = new Set(${JSON.stringify(Object.keys(blocks))});\n`);
console.log(`gen-hardcoded-previews: ${Object.keys(blocks).length} previews`);
